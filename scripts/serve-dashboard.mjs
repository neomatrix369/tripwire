#!/usr/bin/env node
/**
 * Local dashboard server: static Mock dashboard + optional Supabase REST proxy.
 *
 * Why: browser Live mode needs an anon key. If SUPABASE_ANON_KEY is unset but
 * SUPABASE_SERVICE_ROLE_KEY exists in .env, this server proxies /rest/v1/* to
 * Supabase and injects the key server-side (bound to 127.0.0.1 only).
 *
 * Prefer SUPABASE_ANON_KEY when present (RLS-gated). Never puts service_role
 * into the browser config.
 *
 * Usage (repo root):
 *   node scripts/serve-dashboard.mjs
 *   node scripts/serve-dashboard.mjs --port 8765
 */
import { createServer } from 'node:http';
import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { extname, join, normalize, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const DASHBOARD = join(ROOT, 'prototypes', 'dc-dashboard');
const ENV_FILE = join(ROOT, '.env');
const CONFIG_OUT = join(DASHBOARD, 'tripwire-dashboard.config.js');
const PROXY_TOKEN = 'local-dashboard-proxy';

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
};

function loadEnv(path) {
  const env = {};
  if (!existsSync(path)) return env;
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#') || !trimmed.includes('=')) continue;
    const i = trimmed.indexOf('=');
    const key = trimmed.slice(0, i).trim();
    let val = trimmed.slice(i + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    env[key] = val;
  }
  return env;
}

function parseArgs(argv) {
  let port = 8765;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--port' && argv[i + 1]) {
      port = Number(argv[++i]);
    }
  }
  return { port };
}

function writeBrowserConfig(origin, liveEnabled) {
  const body = `// Auto-generated by scripts/serve-dashboard.mjs — gitignored, do NOT commit.
// Browser talks to this local origin; the server proxies /rest/v1 to Supabase.
window.__TRIPWIRE_CONFIG = {
  SUPABASE_URL: ${JSON.stringify(liveEnabled ? origin : '')},
  SUPABASE_ANON_KEY: ${JSON.stringify(liveEnabled ? PROXY_TOKEN : '')},
};
`;
  writeFileSync(CONFIG_OUT, body, 'utf8');
}

function safeStaticPath(urlPath) {
  const decoded = decodeURIComponent((urlPath || '/').split('?')[0]);
  const rel = decoded === '/' ? 'Tripwire.dc.html' : decoded.replace(/^\//, '');
  const full = resolve(DASHBOARD, rel);
  const rootWithSep = DASHBOARD.endsWith(sep) ? DASHBOARD : DASHBOARD + sep;
  if (full !== DASHBOARD && !full.startsWith(rootWithSep)) return null;
  return full;
}

async function proxyRest(req, res, upstreamBase, apiKey) {
  const target = `${upstreamBase}${req.url}`;
  const headers = {
    apikey: apiKey,
    Authorization: `Bearer ${apiKey}`,
  };
  if (req.headers.accept) headers.Accept = req.headers.accept;
  if (req.headers['content-type']) headers['Content-Type'] = req.headers['content-type'];
  if (req.headers.prefer) headers.Prefer = req.headers.prefer;

  const upstream = await fetch(target, {
    method: req.method,
    headers,
  });
  const buf = Buffer.from(await upstream.arrayBuffer());
  const outHeaders = {
    'Content-Type': upstream.headers.get('content-type') || 'application/json',
    'Access-Control-Allow-Origin': '*',
  };
  const contentRange = upstream.headers.get('content-range');
  if (contentRange) outHeaders['Content-Range'] = contentRange;
  res.writeHead(upstream.status, outHeaders);
  res.end(buf);
}

function serveStatic(req, res) {
  const full = safeStaticPath(req.url);
  if (!full || !existsSync(full) || !statSync(full).isFile()) {
    res.writeHead(404, { 'Content-Type': 'text/plain; charset=utf-8' });
    res.end('Not found');
    return;
  }
  const ext = extname(full);
  res.writeHead(200, { 'Content-Type': MIME[ext] || 'application/octet-stream' });
  res.end(readFileSync(full));
}

const { port } = parseArgs(process.argv.slice(2));
const env = loadEnv(ENV_FILE);
const supabaseUrl = (env.SUPABASE_URL || '').replace(/\/$/, '');
const anonKey = env.SUPABASE_ANON_KEY || '';
const serviceKey = env.SUPABASE_SERVICE_ROLE_KEY || '';
const apiKey = anonKey || serviceKey;
const keyMode = anonKey ? 'anon' : serviceKey ? 'service_role (local proxy only)' : '';
const liveEnabled = Boolean(supabaseUrl && apiKey);

const origin = `http://127.0.0.1:${port}`;
writeBrowserConfig(origin, liveEnabled);

const server = createServer(async (req, res) => {
  try {
    if (req.method === 'OPTIONS') {
      res.writeHead(204, {
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Headers': 'apikey, authorization, content-type, prefer',
        'Access-Control-Allow-Methods': 'GET,HEAD,OPTIONS',
      });
      res.end();
      return;
    }
    if (req.url && req.url.startsWith('/rest/v1/')) {
      if (!liveEnabled) {
        res.writeHead(503, { 'Content-Type': 'text/plain; charset=utf-8' });
        res.end('Live dashboard requires SUPABASE_URL and a Supabase API key in .env');
        return;
      }
      await proxyRest(req, res, supabaseUrl, apiKey);
      return;
    }
    serveStatic(req, res);
  } catch (err) {
    console.error('[serve-dashboard]', err.message);
    res.writeHead(502, { 'Content-Type': 'text/plain; charset=utf-8' });
    res.end(`Proxy error: ${err.message}`);
  }
});

server.listen(port, '127.0.0.1', () => {
  console.log(`Tripwire dashboard on ${origin}`);
  if (liveEnabled) {
    console.log(`  Live proxy upstream: ${supabaseUrl}`);
    console.log(`  auth mode: ${keyMode}`);
    console.log(`  config: ${relative(ROOT, CONFIG_OUT)} (proxy token, no secrets in browser)`);
    console.log(`Open: ${origin}/Tripwire.dc.html  → Mock by default; select Live (Supabase) when needed`);
  } else {
    console.log('  mode: Mock demo data (no Supabase configuration found)');
    console.log(`Open: ${origin}/Tripwire.dc.html  → configure Supabase to enable Live`);
  }
});
